@router.get(
    "/{review_run_id}/feedback",
    response_model=list[FeedbackResponse],
    summary="List Review Run Feedback",
    description="Returns developer and reviewer feedback linked to this review run.",
)
async def list_review_run_feedback(
    review_run_id: uuid.UUID,
    session: Annotated[AsyncSession, Depends(get_db_session)],
    limit: Annotated[int, Query(ge=1, le=500)] = 100,
    offset: Annotated[int, Query(ge=0)] = 0,
) -> list[FeedbackResponse]:
    """List feedback recorded for a review run."""
    run = await dashboard_service.get_review_run(session, review_run_id)
    if run is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"ReviewRun {review_run_id} not found",
        )
    filter_params = FeedbackFilter(review_run_id=review_run_id)
    return await dashboard_service.list_feedback(
        session, filter_params=filter_params, limit=limit, offset=offset
    )
